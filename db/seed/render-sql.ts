/**
 * Renders the reference seed (teams, stadiums) as idempotent SQL for a custom
 * drizzle migration. The migration file is committed; tests assert it matches
 * this renderer, so the seed and the migration can't drift apart.
 *
 * To change seed data later: edit reference-data.ts, create a NEW custom
 * migration (`npx drizzle-kit generate --custom --name=...`), point
 * SEED_MIGRATION at it and run `npm run db:seed-sql`.
 */
import { STADIUMS, TEAMS } from "./reference-data";

export const SEED_MIGRATION = "0002_seed_teams_stadiums.sql";

const BREAK = "--> statement-breakpoint";

function lit(v: string | number | boolean | null): string {
  if (v === null) return "NULL";
  if (typeof v === "boolean") return v ? "1" : "0";
  if (typeof v === "number") {
    if (!Number.isFinite(v)) throw new Error(`non-finite number in seed: ${v}`);
    return String(v);
  }
  return `'${v.replace(/\\/g, "\\\\").replace(/'/g, "''")}'`;
}

function upsert(
  table: string,
  cols: string[],
  rows: Array<Array<string | number | boolean | null>>,
) {
  const values = rows.map((r) => `  (${r.map(lit).join(", ")})`).join(",\n");
  const updates = cols
    .slice(1)
    .map((c) => `\`${c}\` = VALUES(\`${c}\`)`)
    .join(", ");
  return (
    `INSERT INTO \`${table}\` (${cols.map((c) => `\`${c}\``).join(", ")}) VALUES\n${values}\n` +
    `ON DUPLICATE KEY UPDATE ${updates};`
  );
}

export function renderSeedSql(): string {
  const teamId = new Map(TEAMS.map((t) => [t.abbr, t.id]));
  const teamSql = upsert(
    "teams",
    ["id", "abbr", "name", "city", "conference", "division", "primary_color", "secondary_color"],
    TEAMS.map((t) => [
      t.id,
      t.abbr,
      t.name,
      t.city,
      t.conference,
      t.division,
      t.primaryColor,
      t.secondaryColor,
    ]),
  );
  const stadiumSql = upsert(
    "stadiums",
    [
      "id",
      "name",
      "team_id",
      "lat",
      "lon",
      "roof_type",
      "surface",
      "altitude_m",
      "timezone",
      "is_active",
    ],
    STADIUMS.map((s) => {
      const tid = s.team === null ? null : teamId.get(s.team);
      if (tid === undefined) throw new Error(`stadium ${s.id}: unknown team ${s.team}`);
      return [
        s.id,
        s.name,
        tid,
        s.lat,
        s.lon,
        s.roofType,
        s.surface,
        s.altitudeM,
        s.timezone,
        s.isActive,
      ];
    }),
  );
  return [
    "-- Generated by `npm run db:seed-sql` from db/seed/reference-data.ts. Do not edit by hand.",
    `${teamSql}\n${BREAK}`,
    `${stadiumSql}\n`,
  ].join("\n");
}
